export default function LibraryPage() {
  const router = useRouter();
  const [items, setItems] = useState<LibraryItem[]>(initialItems);
  const [search, setSearch] = useState("");
  const [filter, setFilter] = useState<"all" | "chat" | "image" | "file" | "agent_output">("all");
  const [sort, setSort] = useState<"recent" | "oldest" | "name">("recent");
  const [view, setView] = useState<"grid" | "list">("grid");

  const filteredItems = items
    .filter((item) => {
      const matchesSearch = item.title.toLowerCase().includes(search.toLowerCase());
      const matchesFilter = filter === "all" || item.type === filter;
      return matchesSearch && matchesFilter;
    })
    .sort((a, b) => {
      if (sort === "name") return a.title.localeCompare(b.title);
      const dateA = new Date(a.createdAt).getTime();
      const dateB = new Date(b.createdAt).getTime();
      return sort === "recent" ? dateB - dateA : dateA - dateB;
    });

  const handleOpen = (id: string) => {
    const item = items.find((i) => i.id === id);
    if (!item) return;

    const routes: Record<LibraryItem["type"], string> = {
      chat: "/ai/chat",
      image: "/ai/image",
      file: "/ai/documents",
      agent_output: "/ai/agents",
    };
    router.push(routes[item.type]);
  };

  const handleToggleFavorite = (id: string) => {
    setItems((prev) =>
      prev.map((i) => (i.id === id ? { ...i, favorite: !i.favorite } : i))
    );
  };

  const handleDownload = (id: string) => {
    console.log("downloading", id);
  };

  const handleDelete = (id: string) => {
    setItems((prev) => prev.filter((i) => i.id !== id));
  };

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1 className="text-2xl font-semibold">Library</h1>
        <p className="text-sm text-muted-foreground mt-1">
          Everything you've created — chats, images, files, and agent outputs — in one place.
        </p>
      </div>

      <LibraryFilterBar
        filter={filter}
        onFilterChange={setFilter}
        search={search}
        onSearchChange={setSearch}
        sort={sort}
        onSortChange={setSort}
        view={view}
        onViewChange={setView}
      />

      {filteredItems.length === 0 ? (
        <LibraryEmptyState hasFilters={search.trim().length > 0 || filter !== "all"} />
      ) : view === "grid" ? (
        <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
          {filteredItems.map((item) => (
            <LibraryItemCard
              key={item.id}
              item={item}
              onOpen={handleOpen}
              onToggleFavorite={handleToggleFavorite}
              onDownload={handleDownload}
              onDelete={handleDelete}
            />
          ))}
        </div>
      ) : (
        <div className="flex flex-col divide-y rounded-xl border">
          {filteredItems.map((item) => (
            <div
              key={item.id}
              className="flex items-center gap-3 p-4 hover:bg-accent/50 cursor-pointer"
              onClick={() => handleOpen(item.id)}
            >
              {item.type === "image" && item.preview ? (
                <img
                  src={item.preview}
                  alt={item.title}
                  className="h-10 w-10 rounded-lg object-cover shrink-0"
                />
              ) : (
                <span className="flex h-10 w-10 shrink-0 items-center justify-center rounded-lg bg-muted" />
              )}
              <div className="flex-1 min-w-0">
                <p className="text-sm font-medium truncate">{item.title}</p>
                <p className="text-xs text-muted-foreground truncate">{item.subtitle}</p>
              </div>
              <LibraryTypeBadge type={item.type} />
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
"use client";

import { MoreHorizontal, Download, Trash2, ExternalLink, Star } from "lucide-react";

import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";

import { LibraryTypeBadge, typeConfig, type LibraryItemType } from "./library-type-badge";

export interface LibraryItem {
  id: string;
  type: LibraryItemType;
  title: string;
  preview?: string; // image thumbnail URL, only for type === "image"
  subtitle: string; // e.g. "Generated by Sonnet 5", file size, source chat
  createdAt: string;
  favorite: boolean;
}

interface LibraryItemCardProps {
  item: LibraryItem;
  onOpen?: (id: string) => void;
  onToggleFavorite?: (id: string) => void;
  onDownload?: (id: string) => void;
  onDelete?: (id: string) => void;
}

export function LibraryItemCard({
  item,
  onOpen,
  onToggleFavorite,
  onDownload,
  onDelete,
}: LibraryItemCardProps) {
  const Icon = typeConfig[item.type].icon;

  return (
    <Card
      className="rounded-xl group overflow-hidden cursor-pointer hover:border-foreground/20 transition-colors pt-0"
      onClick={() => onOpen?.(item.id)}
    >
      <div className="relative aspect-video bg-muted flex items-center justify-center">
        {item.type === "image" && item.preview ? (
          <img
            src={item.preview}
            alt={item.title}
            className="h-full w-full object-cover"
          />
        ) : (
          <Icon className="size-8 text-muted-foreground/50" />
        )}

        <button
          onClick={(e) => {
            e.stopPropagation();
            onToggleFavorite?.(item.id);
          }}
          className="absolute top-2 right-2 flex h-7 w-7 items-center justify-center rounded-full bg-background/80 backdrop-blur opacity-0 group-hover:opacity-100 transition-opacity"
        >
          <Star
            className={`size-3.5 ${item.favorite ? "fill-amber-400 text-amber-400" : "text-muted-foreground"}`}
          />
        </button>
      </div>

      <CardContent className="pt-3 pb-4">
        <div className="flex items-start justify-between gap-2">
          <div className="min-w-0 flex-1">
            <p className="text-sm font-medium truncate">{item.title}</p>
            <p className="text-xs text-muted-foreground truncate mt-0.5">
              {item.subtitle}
            </p>
          </div>

          <DropdownMenu>
            <DropdownMenuTrigger asChild onClick={(e) => e.stopPropagation()}>
              <Button
                variant="ghost"
                size="icon"
                className="size-7 shrink-0 opacity-0 group-hover:opacity-100 transition-opacity"
              >
                <MoreHorizontal className="size-4" />
              </Button>
            </DropdownMenuTrigger>
            <DropdownMenuContent
              align="end"
              className="w-44 rounded-xl p-1.5"
              onClick={(e) => e.stopPropagation()}
            >
              <DropdownMenuItem
                className="gap-2 rounded-lg h-9"
                onClick={() => onOpen?.(item.id)}
              >
                <ExternalLink className="size-4" />
                Open
              </DropdownMenuItem>
              <DropdownMenuItem
                className="gap-2 rounded-lg h-9"
                onClick={() => onDownload?.(item.id)}
              >
                <Download className="size-4" />
                Download
              </DropdownMenuItem>
              <DropdownMenuSeparator className="my-1" />
              <DropdownMenuItem
                className="gap-2 rounded-lg h-9 text-destructive focus:text-destructive"
                onClick={() => onDelete?.(item.id)}
              >
                <Trash2 className="size-4" />
                Delete
              </DropdownMenuItem>
            </DropdownMenuContent>
          </DropdownMenu>
        </div>

        <div className="mt-2">
          <LibraryTypeBadge type={item.type} />
        </div>
      </CardContent>
    </Card>
  );
}